/// Complete 8-language offline localizer (`en`, `hi`, `kn`, `ta`, `te`, `ml`,
/// `mr`, `bn`) for all Assistive Dial menus, option announcements, system
/// prompts, status messages, and error notices.
class DialLocalizer {
  const DialLocalizer._();

  static String _lang(String locale) => OpenetraLocalizer.langCode(locale);

  /// Localized option title for spoken & status announcements.
  static String optionTitle(DialOption option, String locale) {
    final lang = _lang(locale);
    if (lang == 'en') return option.title;
    return _optionTitles[option.id]?[lang] ?? option.title;
  }

  /// Localized option description for detailed spoken announcements.
  /// Returns empty string for non-English options without a dedicated subtitle
  /// so English sentences never leak into Indic TTS output.
  static String optionDescription(DialOption option, String locale) {
    final lang = _lang(locale);
    if (lang == 'en') return option.spokenDescription;
    return _optionDescriptions[option.id]?[lang] ?? '';
  }

  /// Localized menu node title (e.g., "Main Dial", "Read Text").
  static String menuTitle(DialMenuNode menu, String locale) {
    final lang = _lang(locale);
    if (lang == 'en') return menu.title;
    return _menuTitles[menu.id]?[lang] ?? menu.title;
  }

  /// Localized submenu intro sentence.
  static String menuIntro(DialMenuNode menu, String locale) {
    final lang = _lang(locale);
    if (lang == 'en') return menu.spokenIntro;
    return _menuIntros[menu.id]?[lang] ?? menu.spokenIntro;
  }

  /// Full spoken announcement for a focused dial option in the active language.
  static String optionAnnouncement(
    DialOption option, {
    required String locale,
    bool detailed = true,
  }) {
    final title = optionTitle(option, locale);
    if (!detailed) return title;
    final desc = optionDescription(option, locale);
    final isSub = option.kind == DialOptionKind.submenu;
    final lang = _lang(locale);
    if (lang == 'en') {
      final hint = isSub ? ' Opens submenu.' : '';
      return '$title. $desc$hint';
    }
    final parts = <String>[title];
    if (desc.isNotEmpty) parts.add(desc);
    if (isSub && (_opensSubmenu[lang]?.isNotEmpty ?? false)) {
      parts.add(_opensSubmenu[lang]!);
    }
    return parts.join(' ');
  }

