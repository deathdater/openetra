  /// Translates a common visual perception term into [lang] (`hi`, `kn`, `ta`,
  /// `te`, `ml`, `mr`, `bn`), falling back cleanly to the original word if not
  /// in the offline lexicon.
  static String translateTerm(String englishTerm, String lang) {
    if (lang == 'en') return englishTerm;
    final clean = englishTerm.trim().toLowerCase();
    final exact = _terms[clean]?[lang];
    if (exact != null) return exact;
    // Try stripping trailing plural 's' for simple matches
    if (clean.endsWith('s') && clean.length > 3) {
      final singular = clean.substring(0, clean.length - 1);
      final match = _terms[singular]?[lang];
      if (match != null) return match;
    }
    return englishTerm.trim();
  }
